/** Writes the Remotion entry file for a project and the webpack settings it needs. */
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import type { WebpackOverrideFn } from "@remotion/bundler";
import { PKG_ROOT, listVideos, readJson, type Project, type Timing } from "../project";

/** Lets user draw files and the generated entry import `eigencast/...` wherever the package is installed. */
export const webpackOverride: WebpackOverrideFn = (config) => ({
  ...config,
  resolve: {
    ...config.resolve,
    alias: { ...(config.resolve?.alias as Record<string, string>), eigencast: join(PKG_ROOT, "src") },
  },
});

const rel = (from: string, to: string) => {
  const r = relative(from, to).split("\\").join("/");
  return r.startsWith(".") ? r : `./${r}`;
};

/**
 * Generate .eigencast/entry.ts listing every video.
 * 1. For each video: import its draw module and timing.json (empty timing if not recorded yet).
 * 2. Import each recorded clip that exists on disk, so webpack bundles the wav.
 * 3. registerRoot(makeRoot(...)) so Remotion sees one composition per video.
 */
export function writeEntry(project: Project): string {
  mkdirSync(project.workDir, { recursive: true });
  const lines: string[] = [`import { registerRoot } from "remotion";`, `import { makeRoot } from "eigencast/stage";`];
  const items: string[] = [];
  listVideos(project).forEach((v, i) => {
    lines.push(`import * as draw${i} from "${rel(project.workDir, v.drawFile!)}";`);
    const timing = readJson<Timing>(v.timingFile, { beats: {} });
    const clips = Object.keys(timing.beats).filter((id) => existsSync(join(v.audioDir, `${id}.wav`)));
    clips.forEach((id) => lines.push(`import a${i}_${id} from "${rel(project.workDir, join(v.audioDir, `${id}.wav`))}";`));
    const audio = clips.map((id) => `${JSON.stringify(id)}: a${i}_${id}`).join(", ");
    items.push(`  { slug: ${JSON.stringify(v.slug)}, module: draw${i}, timing: ${JSON.stringify(timing)}, audio: { ${audio} } },`);
  });
  const src = `// Generated by eigencast. Do not edit; it is rewritten before every preview and render.\n${lines.join("\n")}\n\nregisterRoot(makeRoot([\n${items.join("\n")}\n], ${project.config.fps}));\n`;
  const file = join(project.workDir, "entry.ts");
  writeFileSync(file, src);
  return file;
}

/**
 * Remotion config for `remotion studio`, which only takes webpack settings from a config file.
 * Remotion compiles config files to CommonJS, so this one can't import our ESM modules:
 * it repeats the alias from webpackOverride with the package path written in.
 */
export function writeStudioConfig(project: Project): string {
  const file = join(project.workDir, "remotion.config.ts");
  const alias = JSON.stringify(join(PKG_ROOT, "src"));
  writeFileSync(
    file,
    `import { Config } from "@remotion/cli/config";\n` +
      `Config.overrideWebpackConfig((c) => ({ ...c, resolve: { ...c.resolve, alias: { ...(c.resolve?.alias as object), eigencast: ${alias} } } }));\n` +
      `Config.setVideoImageFormat("jpeg");\n`,
  );
  return file;
}
